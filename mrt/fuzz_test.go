func FuzzDecodeTableDumpV2(f *testing.F) {
	now := time.Date(2024, 1, 1, 0, 0, 0, 0, time.UTC)

	seeds := func() [][]byte {
		var seeds [][]byte

		// Peer index table
		peerIndex := NewMrtTableDumpV2_PeerIndex(net.ParseIP("1.2.3.4").To4(), "test", now)
		peerIndex.AddPeer(net.ParseIP("10.0.0.1").To4(), 64500, net.ParseIP("10.0.0.1").To4())
		var buf bytes.Buffer
		peerIndex.Write(&buf)
		seeds = append(seeds, buf.Bytes())

		// RIB IPv4 unicast
		_, pfx, _ := net.ParseCIDR("10.0.0.0/24")
		nlri := messages.NLRI_IPPrefix{Prefix: *pfx}
		rib := NewMrtTableDumpV2_RibAfiSafi(0, messages.AFI_IPV4, messages.SAFI_UNICAST, nlri, now)
		rib.AddEntry(0, now, []messages.BGPAttributeIf{
			messages.BGPAttribute_ORIGIN{Origin: 2},
		})
		buf.Reset()
		rib.Write(&buf)
		seeds = append(seeds, buf.Bytes())

		// Generic RIB
		rib2 := NewMrtTableDumpV2_RibGeneric(0, messages.AFI_IPV6, messages.SAFI_UNICAST, nlri, now)
		buf.Reset()
		rib2.Write(&buf)
		seeds = append(seeds, buf.Bytes())

		seeds = append(seeds, []byte{})
		seeds = append(seeds, []byte{0, 0, 0, 0})

		return seeds
	}()

	for _, s := range seeds {
		f.Add(s)
	}

	f.Fuzz(func(t *testing.T, data []byte) {
		r := bytes.NewReader(data)
		header := make([]byte, 12)
		if _, err := r.Read(header); err != nil {
			return
		}
		timestamp := uint32(header[0])<<24 | uint32(header[1])<<16 | uint32(header[2])<<8 | uint32(header[3])
		mrttype := uint16(header[4])<<8 | uint16(header[5])
		subtype := uint16(header[6])<<8 | uint16(header[7])
		length := uint32(header[8])<<24 | uint32(header[9])<<16 | uint32(header[10])<<8 | uint32(header[11])

		ts := time.Unix(int64(timestamp), 0)

		switch mrttype {
		case TYPE_TABLE_DUMPV2:
			_, _ = DecodeBGP4TD2(r, ts, subtype, length)
		case TYPE_BGP4MP:
			_, _ = DecodeBGP4MP(r, ts, subtype, length)
		}
	})
}

func uint32ToBytes(v uint32) []byte {
	return []byte{byte(v >> 24), byte(v >> 16), byte(v >> 8), byte(v)}
}

func uint16ToBytes(v uint16) []byte {
	return []byte{byte(v >> 8), byte(v)}
}
